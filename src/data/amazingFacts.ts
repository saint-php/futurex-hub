/** Pick a stable "fact of the day" from the list based on date */
export function getFactOfTheDay(): AmazingFact {
  const dayIndex = Math.floor(Date.now() / (1000 * 60 * 60 * 24));
  return amazingFacts[dayIndex % amazingFacts.length];
}

export function getFactsByCategory(category: string): AmazingFact[] {
  return amazingFacts.filter(
    (f) => f.category.toLowerCase() === category.toLowerCase()
  );
}
